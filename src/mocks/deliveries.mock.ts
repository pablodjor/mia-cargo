function takePackageIds(start: number, count: number): string[] {
  return packagesMock.slice(start, start + count).map((pkg) => pkg.id)
}

function deliveredStops(packageIds: string[], date: string, startHour = 9): Delivery['stops'] {
  return packageIds.map((packageId, index) => ({
    packageId,
    order: index + 1,
    status: 'delivered' as const,
    attemptedAt: `${date}T${String(startHour + Math.floor(index / 3)).padStart(2, '0')}:${String((index * 11) % 60).padStart(2, '0')}:00.000Z`,
  }))
}

